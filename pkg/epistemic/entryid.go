// Package epistemic provides deterministic knowledge hashing — EntryID.
//
// Same fact + same origin + same epistemic trust = same ID. Always.
// Used by Citadel for deduplication and by agents for cross-referencing facts.
//
// Formula: SHA256(namespace || content || origin || epistemic)[:16]
package epistemic

import (
	"crypto/sha256"
	"encoding/hex"
)

// Origin describes where knowledge came from.
type Origin string

const (
	// OriginSelf — created by the agent itself.
	OriginSelf Origin = "self"

	// OriginExternal — from an external source (API, import, human).
	OriginExternal Origin = "external"

	// OriginDerived — generated by the system (scanner, dream worker, inference).
	OriginDerived Origin = "derived"
)

// EntryID computes a deterministic 16-hex-char ID for a knowledge entry.
//
// Same (room, content, origin, epistemic) → same ID always.
// Different origin → different ID (anti-spoofing).
//
// Used by Citadel for:
//   - Deduplication (same fact can't be stored twice)
//   - Citability (Agent A: "I know X (id: a1b2...)", Agent B looks up a1b2...)
//   - Merging (same facts merge, different don't conflict)
func EntryID(room, content string, origin Origin, epistemic string) string {
	h := sha256.New()
	h.Write([]byte(room))
	h.Write([]byte(content))
	h.Write([]byte(origin))
	h.Write([]byte(epistemic))
	return hex.EncodeToString(h.Sum(nil))[:16]
}
